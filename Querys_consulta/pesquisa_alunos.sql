/* Parâmetros Necessários:
    - Usuario tecnico TOTVS:
    - Senha TOTVS:
    - RA:
    - IDHABILITACAOFILIAL:
    - IDPERLET:
*/

SELECT  
        SMATRICPL.CODCOLIGADA AS V_COLIGADA,
        SMATRICPL.CODFILIAL AS V_CODFILIAL,
    /*ALUNO*/
        SMATRICPL.RA AS V_RA,
        SALUNO.CODPESSOA AS V_CODPESSOA,
        PPESSOA.NOME AS V_NOMEALUNO,
    /*PERÍODO LETIVO*/
        SHABILITACAOFILIAL.IDHABILITACAOFILIAL AS V_IDHABILITACAOFILIAL,
        SMATRICPL.IDPERLET AS V_IDPERLET,
        SPLETIVO.CODPERLET AS V_CODPERLET,
        SPLETIVO.DESCRICAO AS V_PERIODOLETIVO,
        SPLETIVO.CODTIPOCURSO AS V_CODTIPOCURSO,
        SHABILITACAOFILIAL.CODTIPOCURSO AS V_CODTIPOCURSO,
        STURMA.CODTURMA AS V_CODTURMA,
    /*MATRÍCULA*/
        SSTATUS.DESCRICAO AS V_STATUS,
    /*CURSO*/
        SHABILITACAOFILIAL.CODCURSO AS V_CODCURSO,
        SCURSO.NOME AS V_NOMECURSO
FROM    SMATRICPL
            INNER JOIN SALUNO 
                ON SMATRICPL.CODCOLIGADA = SALUNO.CODCOLIGADA
                AND SMATRICPL.RA = SALUNO.RA
            INNER JOIN SSTATUS 
                ON SMATRICPL.CODCOLIGADA = SSTATUS.CODCOLIGADA
                AND SMATRICPL.CODSTATUS = SSTATUS.CODSTATUS
            INNER JOIN PPESSOA
                ON SALUNO.CODPESSOA = PPESSOA.CODIGO
            INNER JOIN STURMA
                ON SMATRICPL.CODCOLIGADA = STURMA.CODCOLIGADA
                AND SMATRICPL.CODFILIAL = STURMA.CODFILIAL
                AND SMATRICPL.CODTURMA = STURMA.CODTURMA
                AND SMATRICPL.IDPERLET = STURMA.IDPERLET
            INNER JOIN SHABILITACAOFILIAL
                ON STURMA.CODCOLIGADA = SHABILITACAOFILIAL.CODCOLIGADA
                AND STURMA.IDHABILITACAOFILIAL = SHABILITACAOFILIAL.IDHABILITACAOFILIAL
            INNER JOIN SPLETIVO
                ON STURMA.CODCOLIGADA = SPLETIVO.CODCOLIGADA
                AND STURMA.IDPERLET = SPLETIVO.IDPERLET
            INNER JOIN SCURSO
                ON SHABILITACAOFILIAL.CODCOLIGADA = SCURSO.CODCOLIGADA
                AND SHABILITACAOFILIAL.CODCURSO = SCURSO.CODCURSO
WHERE SMATRICPL.CODCOLIGADA = 1
--AND SSTATUS.DESCRICAO IN ('ATIVO','MATRICULADO')
AND SMATRICPL.RA IN (
'10322644',
'10238118',
'10276946',
'10174710',
'10080331',
'10292740',
'10106872',
'10174710',
'10190500',
'10358688',
'10736324',
'10726925',
'10741479'
)
ORDER BY 3

